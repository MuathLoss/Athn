def shared_features(ref, other):
    a = cv2.imread('/content/images/small/' + image_paths[ref], 0)
    b = cv2.imread('/content/images/small/' + image_paths[other], 0)

    k1, d1 = sift.detectAndCompute(a, None)
    k2, d2 = sift.detectAndCompute(b, None)

    if d1 is None or d2 is None or len(d2) < 2:
        return 0

    matches = [m for m, n in matcher.knnMatch(d1, d2, k=2)
               if m.distance < 0.75 * n.distance]

    if len(matches) < 4:
        return 0

    src = np.float32([k1[m.queryIdx].pt for m in matches])
    dst = np.float32([k2[m.trainIdx].pt for m in matches])

    _, mask = cv2.findHomography(src, dst, cv2.RANSAC, 3.0)

    return int(mask.sum()) if mask is not None else 0

