from PIL import Image, ImageOps, ImageEnhance, ImageDraw
from io import BytesIO
import random

def manipulate(img, image_id):
    rng = random.Random(image_id)
    img = img.convert('RGB')
    w, h = img.size

    # 1. Color change and compression
    color = ImageEnhance.Color(img).enhance(rng.uniform(0.3, 1.7))
    buffer = BytesIO()
    color.save(buffer, format='JPEG', quality=30)
    buffer.seek(0)
    compressed = Image.open(buffer).copy()

    # 2. Rotation and mirroring
    rotated = ImageOps.mirror(
        img.rotate(rng.uniform(-25, 25), fillcolor='white')
    )

    # 3. Cropping
    c = rng.uniform(0.1, 0.25)
    cropped = img.crop((
        int(w * c),
        int(h * c),
        int(w * (1 - c)),
        int(h * (1 - c))
    ))

    # 4. Text overlay
    overlay = img.copy()
    draw = ImageDraw.Draw(overlay)
    draw.rectangle(
        (int(w * 0.15), int(h * 0.45), int(w * 0.85), int(h * 0.65)),
        fill='black'
    )
    draw.text(
        (int(w * 0.2), int(h * 0.5)),
        'SPECIAL OFFER',
        fill='white'
    )

    # 5. Combined manipulation
    combined = ImageOps.mirror(cropped)
    combined = ImageEnhance.Contrast(combined).enhance(1.5)
    combined = combined.rotate(15, fillcolor='white')

    return {
        'compressed': compressed,
        'rotated': rotated,
        'cropped': cropped,
        'overlay': overlay,
        'combined': combined
    }

