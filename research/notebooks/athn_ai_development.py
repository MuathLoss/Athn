def verify_regions(query, reference):
    k1, d1 = features(query)
    k2, d2 = features(reference)

    if d1 is None or d2 is None or len(d2) < 2:
        return 0, 0

    matches = [
        m for m, n in matcher.knnMatch(d1, d2, k=2)
        if m.distance < 0.75 * n.distance
    ]

    if len(matches) < 4:
        return 0, 0

    src = np.float32([k1[m.queryIdx].pt for m in matches])
    dst = np.float32([k2[m.trainIdx].pt for m in matches])

    _, mask = cv2.findHomography(src, dst, cv2.RANSAC, 3.0)

    count = int(mask.sum()) if mask is not None else 0

    return count, count / len(matches)

